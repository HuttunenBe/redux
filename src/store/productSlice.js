// Import functions from Redux Toolkit
// createSlice: to create a slice of Redux state with reducers
// createAsyncThunk: to handle async actions like API calls
import { createAsyncThunk, createSlice } from "@reduxjs/toolkit";

// Import axios to make HTTP requests
import axios from "axios";

// Initial state for the products slice
const initialState = {
  products: [], // array to store fetched products
  loading: false, // boolean to track loading state (optional in this code)
};

// API endpoint to fetch products
const api = "https://fakestoreapi.com/products";

// createAsyncThunk generates async Redux actions (pending, fulfilled, rejected)
export const fetchProducts = createAsyncThunk(
  "products/products", // action type prefix
  async () => {
    // Make GET request to the API
    const response = await axios.get(api);
    // Return the data to be used in the fulfilled reducer
    return response.data;
  }
);

// Create the product slice
const productSlice = createSlice({
  name: "products",      // slice name
  initialState,          // initial state defined above
  reducers: {},          // no regular reducers needed for this slice
  extraReducers(builder) {
    // Handle async actions generated by createAsyncThunk
    builder.addCase(fetchProducts.fulfilled, (state, action) => {
      // When fetchProducts succeeds, store the fetched products in state
      state.products = action.payload;
      // You could also handle loading or errors here if needed
    });
  },
});

// Export the reducer to add to the Redux store
export default productSlice.reducer;
